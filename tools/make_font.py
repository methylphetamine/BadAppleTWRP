#!/usr/bin/env python3
"""Render the recovery console font into a bitmap table for fbplayer.

The begonia OrangeFox theme uses twres/fonts/FiraCode-Regular.ttf at 29 px for
its console.  Rendering the same face here keeps the framebuffer player looking
like the console version instead of a generic 8x8 bitmap font.

Cell geometry is 20x36 with the baseline at 28 px.  At 30 px FiraCode has a
~18 px advance and a ~36 px ascent+descent box, so every printable ASCII glyph
fits with a couple of pixels to spare.  fbplayer scales the cells to whatever
the framebuffer reports, so this table is resolution independent.
"""
import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

CELL_W = 20
CELL_H = 36
BASELINE = 28
FIRST = 32
LAST = 126


def render(path, size):
    font = ImageFont.truetype(path, size)
    alpha = font.getmetrics()
    ascent, descent = alpha
    print(f"font metrics: ascent={ascent} descent={descent} box={ascent + descent}", file=sys.stderr)
    table = []
    clipped = []
    empty = []
    widths = set()
    for cp in range(FIRST, LAST + 1):
        ch = chr(cp)
        img = Image.new("L", (CELL_W, CELL_H), 0)
        draw = ImageDraw.Draw(img)
        advance = font.getlength(ch)
        widths.add(round(advance, 2))
        x = (CELL_W - advance) / 2.0
        draw.text((x, BASELINE), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        if box is None:
            empty.append(ch)
        elif box[0] < 0 or box[1] < 0 or box[2] > CELL_W or box[3] > CELL_H:
            clipped.append((ch, box))
        table.append(img.tobytes())
    if clipped:
        for ch, box in clipped:
            print(f"glyph {ch!r} clipped: {box}", file=sys.stderr)
        sys.exit("increase the cell size; glyphs are clipped")
    print(f"advances: {sorted(widths)}", file=sys.stderr)
    print(f"empty glyphs: {''.join(empty)!r}", file=sys.stderr)
    return table


def emit(table, out_path):
    count = len(table)
    size = CELL_W * CELL_H
    lines = [
        "/* Generated by tools/make_font.py - do not edit. */",
        f"#define FONT_W {CELL_W}",
        f"#define FONT_H {CELL_H}",
        f"#define FONT_FIRST {FIRST}",
        f"#define FONT_LAST {LAST}",
        f"#define FONT_GLYPHS {count}",
        f"static const unsigned char font_bits[{count}][{size}] = {{",
    ]
    for glyph in table:
        lines.append("  {")
        for off in range(0, size, CELL_W):
            row = ", ".join(f"{b:3d}" for b in glyph[off:off + CELL_W])
            lines.append("    " + row + ",")
        lines.append("  },")
    lines.append("};")
    with open(out_path, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"{out_path}: {count} glyphs, {size} bytes each", file=sys.stderr)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--font",
        default=os.path.join("..", "of", "ram", "root", "twres", "fonts", "FiraCode-Regular.ttf"),
    )
    ap.add_argument("--size", type=int, default=30)
    ap.add_argument("-o", "--output", default="src/font.h")
    args = ap.parse_args()
    if not os.path.exists(args.font):
        sys.exit(f"font not found: {args.font}")
    emit(render(args.font, args.size), args.output)


if __name__ == "__main__":
    main()
